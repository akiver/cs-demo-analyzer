#!/usr/bin/env bash
# Generates internal/visibility/hitbox_templates.go from every capture of debug/hitboxes/, prints the error report of
# the templates, then formats, vets and tests the packages that use them.
#
# Usage: generate.sh
#
# The demo of a capture has the same name as the capture, in debug/hitboxes/ or in cs-demos/cs2/.
set -euo pipefail

root=$(cd "$(dirname "$0")/../../.." && pwd)
cd "$root"

output=internal/visibility/hitbox_templates.go

args=()
for capture in debug/hitboxes/*.jsonl; do
    if [ ! -f "$capture" ]; then
        echo "No capture in debug/hitboxes/: capture demos first with capture.sh."
        exit 1
    fi

    name=$(basename "$capture" .jsonl)
    demo=""
    for dir in debug/hitboxes cs-demos/cs2; do
        if [ -f "$dir/$name.dem" ]; then
            demo="$dir/$name.dem"
            break
        fi
    done
    if [ -z "$demo" ]; then
        echo "No demo for $capture: put $name.dem in debug/hitboxes/."
        exit 1
    fi

    args+=("$capture" "$demo")
done

# The generator imports the package the generated file belongs to, which doesn't compile without the file. An empty
# set of templates lets it build, and is removed if the generation fails so that it never stays in place of real ones.
has_written_stub=0
if [ ! -f "$output" ]; then
    printf '%s\n' '// Code generated by cmd/hitbox-templates, DO NOT EDIT.' '' 'package visibility' '' \
        'var hitboxTemplates [HitboxTemplateCount]HitboxTemplate' >"$output"
    has_written_stub=1
fi

if ! go run ./cmd/hitbox-templates -report "${args[@]}"; then
    if [ "$has_written_stub" = 1 ]; then
        rm -f "$output"
    fi
    exit 1
fi

echo
echo "Poses per template:"
grep ' poses$' "$output" | sed 's/^[[:space:]]*\/\/ /  /'

echo
unformatted=$(gofmt -l ./internal ./cmd ./pkg)
if [ -n "$unformatted" ]; then
    echo "Not formatted: $unformatted"
    exit 1
fi
go vet ./internal/visibility ./cmd/hitbox-templates ./pkg/...
go test ./internal/visibility/ ./pkg/...
